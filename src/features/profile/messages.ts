export type MessageKey = keyof typeof catalogs['pt-BR']

export function profileMessage(language: string, key: MessageKey, values?: Record<string, string>): string {
  const catalog = language === 'en' ? catalogs.en : catalogs['pt-BR']
  const template: string = catalog[key]
  if (!values) return template
  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, value), template)
}

export function messageCatalogKeys(language: AppliedLanguage): string[] {
  return Object.keys(catalogs[language]).sort()
}
