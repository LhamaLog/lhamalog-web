export type MessageKey = keyof typeof catalogs['pt-BR']

export function profileMessage(language: string, key: MessageKey, values?: Record<string, string>): string {
  const catalog = language === 'en' ? catalogs.en : catalogs['pt-BR']
  const template: string = catalog[key]
  if (!values) return template
  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, value), template)
}

export function messageCatalogKeys(language: AppliedLanguage): string[] {
  return Object.keys(catalogs[language]).sort()
}

export function profileFieldMessages(language: string, profile: Parameters<typeof profileFieldErrors>[0]): Record<string, string> {
  const codes = profileFieldErrors(profile)
  const messages: Record<string, string> = {}
  if (codes.displayName === 'control') messages.displayName = profileMessage(language, 'profile.error.nameControl')
  else if (codes.displayName) messages.displayName = profileMessage(language, 'profile.error.name')
  if (codes.bio === 'control') messages.bio = profileMessage(language, 'profile.error.bioControl')
  else if (codes.bio) messages.bio = profileMessage(language, 'profile.error.bio')
  if (codes.jobTitle === 'control') messages.jobTitle = profileMessage(language, 'profile.error.jobTitleControl')
  else if (codes.jobTitle) messages.jobTitle = profileMessage(language, 'profile.error.jobTitle')
  if (codes.language) messages.language = profileMessage(language, 'profile.error.language')
  if (codes.timezone) messages.timezone = profileMessage(language, 'profile.error.timezone')
  return messages
}
