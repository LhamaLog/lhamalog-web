export type DashboardMessageKey = keyof typeof catalogs['pt-BR']

export function dashboardMessage(
  language: AppliedLanguage,
  key: DashboardMessageKey,
  values: Record<string, string> = {},
): string {
  const catalog = catalogs[language] ?? catalogs['pt-BR']
  let text: string = catalog[key] ?? catalogs['pt-BR'][key]
  for (const [name, value] of Object.entries(values)) {
    text = text.replaceAll(`{${name}}`, value)
  }
  return text
}

export function occurrencesPendingMessage(language: AppliedLanguage = 'pt-BR'): string {
  return dashboardMessage(language, 'dashboard.occurrences.pending')
}
